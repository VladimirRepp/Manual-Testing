#include <iostream>
using namespace std;

/*
Описание:
Небольшая программа интернет-магазина.
Пользователь выбирает товар и количество,
после чего программа рассчитывает стоимость покупки.

Требования:
1. Пользователь должен указать количество товара.
2. Количество должно быть больше 0.
3. Цена одного товара — 500 рублей.
4. Общая стоимость рассчитывается как:
   количество * цена.
5. Если количество некорректное, покупка не должна создаваться.

Задание тестировщика:
1. Протестируйте программу.
2. Найдите хотя бы одну ошибку.
3. Для найденной ошибки составьте Bug Report.
4. Обязательно укажите:
   - Summary
   - Environment
   - Preconditions
   - Steps to Reproduce
   - Test Data
   - Expected Result
   - Actual Result
   - Reproducibility
   - Evidence

Ожидаемый результат / Ключ для преподавателя:
При вводе количества 0 программа не должна создавать покупку.
При отрицательном количестве программа также не должна создавать покупку.

В программе присутствует ошибка:
отрицательное количество принимается программой.

Пример:
Количество: -2
Ожидаемый результат:
Некорректное количество, покупка невозможна.

Фактический результат:
Создается покупка с отрицательной стоимостью.

Пример Bug Report:

Summary:
Отрицательное количество товара позволяет создать покупку.

Environment:
Windows 11, console application, C++.

Preconditions:
Программа запущена.

Steps to Reproduce:
1. Запустить программу.
2. Выбрать покупку товара.
3. Ввести количество -2.
4. Подтвердить покупку.

Test Data:
Количество = -2.

Expected Result:
Программа должна сообщить об ошибке
и не создавать покупку.

Actual Result:
Программа создает покупку и рассчитывает отрицательную стоимость.

Reproducibility:
100%.

Evidence:
Скриншот консоли с введенным -2
и результатом работы программы.
*/

int main()
{
    const int price = 500;

    int quantity;

    cout << "=== Internet Shop ===\n";
    cout << "Product price: " << price << " rubles\n";

    cout << "Enter quantity: ";
    cin >> quantity;

    if (quantity == 0)
    {
        cout << "Error: quantity cannot be zero.\n";
        return 0;
    }

    int total = quantity * price;

    cout << "Purchase created.\n";
    cout << "Quantity: " << quantity << "\n";
    cout << "Total: " << total << " rubles\n";

    return 0;
}