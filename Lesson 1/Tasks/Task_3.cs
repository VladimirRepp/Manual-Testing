using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — GAME ITEM PURCHASE
Язык: C#
Формат: самостоятельная работа
Тема: Test Case и Checklist
============================================================

ОПИСАНИЕ

Игрок покупает игровой предмет за внутриигровые монеты.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Предмет стоит 500 монет.

2. Игрок указывает количество монет.

3. При наличии 500 или более монет покупка возможна.

4. После покупки стоимость предмета вычитается из баланса.

5. При количестве монет меньше 500 покупка невозможна.

6. Баланс не должен становиться отрицательным.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Создайте Test Case и Checklist.

Обязательно проверьте:

- 0 монет;
- меньше 500;
- ровно 500;
- больше 500;
- большое количество монет.

============================================================
*/

class Program
{
    static void BuyItem()
    {
        int coins = 1000;
        int price = 800;

        Console.WriteLine($"Монеты: {coins}");
        Console.WriteLine($"Цена предмета: {price}");

        Console.Write("Количество предметов: ");
        int count = Convert.ToInt32(Console.ReadLine());

        if (count <= 0)
        {
            Console.WriteLine("Количество должно быть больше нуля.");
            return;
        }

        int total = price * count;

        if (coins >= total)
        {
            Console.WriteLine("Покупка выполнена.");
        }
        else
        {
            Console.WriteLine("Недостаточно монет.");
        }
    }

    static void Main()
    {
        int choice;

        do
        {
            Console.WriteLine("\n======= GAME SHOP =======");
            Console.WriteLine("1. Купить предмет");
            Console.WriteLine("0. Выход");

            Console.Write("Выберите действие: ");
            choice = Convert.ToInt32(Console.ReadLine());

            if (choice == 1)
            {
                BuyItem();
            }

        } while (choice != 0);
    }
}
