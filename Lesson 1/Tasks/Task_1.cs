using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — GAME ACCOUNT REGISTRATION
Язык: C#
Формат: разбираем вместе с преподавателем
Тема: Test Case и Checklist
============================================================

ОПИСАНИЕ

Программа имитирует регистрацию аккаунта игрока.

Пользователь вводит логин, пароль и возраст.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Логин обязателен.

2. Длина логина должна быть от 3 до 15 символов
   включительно.

3. Пароль обязателен.

4. Пароль должен содержать минимум 6 символов.

5. Возраст обязателен.

6. Регистрация доступна пользователям от 12 лет.

7. При корректных данных регистрация должна завершаться
   успешно.

8. При некорректных данных регистрация не должна
   завершаться успешно.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Составьте Test Case для регистрации пользователя.

Для каждого Test Case укажите:

- название;
- предусловия;
- тестовые данные;
- шаги;
- ожидаемый результат;
- фактический результат;
- PASS / FAIL.

Дополнительно составьте Checklist для быстрой проверки формы.

Обязательно проверьте:

- корректный логин;
- слишком короткий логин;
- слишком длинный логин;
- пустой логин;
- корректный пароль;
- короткий пароль;
- возраст меньше 12;
- возраст 12;
- возраст больше 12.

------------------------------------------------------------
ОЖИДАЕМЫЙ РЕЗУЛЬТАТ / КЛЮЧ ДЛЯ ПРЕПОДАВАТЕЛЯ
------------------------------------------------------------

Студент должен получить полноценные Test Case,
а не просто список значений.

В Checklist должны быть короткие проверки.

В программе предусмотрена ошибка в одной из проверок
регистрации.

Основной учебный результат:

Test Case должен описывать КАК проверяется требование,
а Checklist — ЧТО необходимо быстро проверить.

============================================================
*/

class Program
{
    static void Register()
    {
        Console.Write("\nВведите логин: ");
        string login = Console.ReadLine();

        Console.Write("Введите пароль: ");
        string password = Console.ReadLine();

        Console.Write("Введите возраст: ");
        int age = Convert.ToInt32(Console.ReadLine());

        if (login.Length < 3 || login.Length > 15)
        {
            Console.WriteLine("Некорректный логин.");
            return;
        }

        if (password.Length < 6)
        {
            Console.WriteLine("Некорректный пароль.");
            return;
        }

        if (age < 12)
        {
            Console.WriteLine("Регистрация запрещена.");
            return;
        }

        Console.WriteLine("Аккаунт успешно создан!");
    }

    static void Main()
    {
        int choice;

        do
        {
            Console.WriteLine("\n======= GAME ACCOUNT =======");
            Console.WriteLine("1. Регистрация");
            Console.WriteLine("0. Выход");

            Console.Write("Выберите действие: ");
            choice = Convert.ToInt32(Console.ReadLine());

            if (choice == 1)
            {
                Register();
            }

        } while (choice != 0);
    }
}
