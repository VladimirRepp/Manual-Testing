#include <iostream>

using namespace std;

void showTerm(int number)
{
    cout << "\n========================================\n";

    switch (number)
    {
        case 1:
            cout << "ПОЗИТИВНОЕ ТЕСТИРОВАНИЕ\n\n";
            cout << "Проверка программы с корректными данными "
                    "и правильными действиями пользователя.\n";
            break;

        case 2:
            cout << "НЕГАТИВНОЕ ТЕСТИРОВАНИЕ\n\n";
            cout << "Проверка поведения программы при некорректных "
                    "данных или неправильных действиях пользователя.\n";
            break;

        case 3:
            cout << "POSITIVE SCENARIO\n\n";
            cout << "Сценарий, в котором пользователь выполняет "
                    "правильные действия и вводит корректные данные.\n";
            break;

        case 4:
            cout << "NEGATIVE SCENARIO\n\n";
            cout << "Сценарий, в котором проверяется реакция программы "
                    "на ошибочные или неожиданные действия.\n";
            break;

        case 5:
            cout << "ВАЛИДНЫЕ ДАННЫЕ\n\n";
            cout << "Данные, которые соответствуют требованиям программы.\n"
                    "Например, возраст 25, если разрешены значения от 18 до 65.\n";
            break;

        case 6:
            cout << "НЕВАЛИДНЫЕ ДАННЫЕ\n\n";
            cout << "Данные, которые не соответствуют требованиям программы.\n"
                    "Например, возраст 15, если минимальный возраст — 18.\n";
            break;

        case 7:
            cout << "КОРРЕКТНЫЙ ВВОД\n\n";
            cout << "Значение введено в допустимом формате и диапазоне.\n";
            break;

        case 8:
            cout << "НЕКОРРЕКТНЫЙ ВВОД\n\n";
            cout << "Значение имеет неправильный формат или находится "
                    "за пределами допустимого диапазона.\n";
            break;

        case 9:
            cout << "ОБЯЗАТЕЛЬНОЕ ПОЛЕ\n\n";
            cout << "Поле, которое пользователь должен заполнить, "
                    "чтобы продолжить выполнение операции.\n";
            break;

        case 10:
            cout << "ВАЛИДАЦИЯ\n\n";
            cout << "Проверка введенных данных на соответствие требованиям.\n";
            break;

        case 11:
            cout << "ERROR MESSAGE\n\n";
            cout << "Сообщение об ошибке, которое программа показывает "
                    "пользователю при возникновении некорректной ситуации.\n";
            break;

        case 12:
            cout << "ОБРАБОТКА ОШИБКИ\n\n";
            cout << "Поведение программы при возникновении ошибки. "
                    "Хорошая программа не должна просто завершаться "
                    "из-за неправильного пользовательского ввода.\n";
            break;

        default:
            cout << "Такого термина нет.\n";
    }

    cout << "========================================\n";
}

void showMenu()
{
    cout << "\n======= ПОЗИТИВНОЕ / НЕГАТИВНОЕ =======\n";
    cout << "1. Позитивное тестирование\n";
    cout << "2. Негативное тестирование\n";
    cout << "3. Positive Scenario\n";
    cout << "4. Negative Scenario\n";
    cout << "5. Валидные данные\n";
    cout << "6. Невалидные данные\n";
    cout << "7. Корректный ввод\n";
    cout << "8. Некорректный ввод\n";
    cout << "9. Обязательное поле\n";
    cout << "10. Валидация\n";
    cout << "11. Error Message\n";
    cout << "12. Обработка ошибки\n";
    cout << "0. Выход\n";
    cout << "=========================================\n";
}

int main()
{
    int choice;

    do
    {
        showMenu();

        cout << "Выберите термин: ";
        cin >> choice;

        if (choice != 0)
        {
            showTerm(choice);
        }

    } while (choice != 0);

    return 0;
}