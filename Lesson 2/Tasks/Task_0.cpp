#include <iostream>
using namespace std;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — BANK TRANSFER
Язык: C++
Формат: разбираем вместе с преподавателем
Тема: Positive / Negative Testing
============================================================

ОПИСАНИЕ

Программа имитирует перевод денег с банковского счёта.

На счёте находится 10000 рублей.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Начальный баланс — 10000 рублей.

2. Сумма перевода должна быть больше 0.

3. Максимальная сумма одного перевода — 10000 рублей.

4. Нельзя перевести сумму больше текущего баланса.

5. При успешном переводе сумма должна вычитаться
   из баланса.

6. При неуспешном переводе баланс не должен изменяться.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Составьте Positive и Negative Test Case.

Positive Testing:

- небольшой корректный перевод;
- перевод всего доступного баланса;
- другие корректные значения.

Negative Testing:

- 0;
- отрицательная сумма;
- сумма больше баланса;
- некорректное значение.

Для каждой проверки укажите:

- входные данные;
- ожидаемый результат;
- фактический результат;
- PASS / FAIL.

------------------------------------------------------------
ОЖИДАЕМЫЙ РЕЗУЛЬТАТ / КЛЮЧ ДЛЯ ПРЕПОДАВАТЕЛЯ
------------------------------------------------------------

Студент должен понимать:

Positive Testing проверяет корректные сценарии.

Negative Testing проверяет реакцию программы
на некорректные данные.

В программе присутствует ошибка обработки одного
из отрицательных сценариев.

Особенно важно проверить, что после неуспешной операции
баланс не изменяется.

============================================================
*/

int balance = 10000;

void transfer()
{
    int amount;

    cout << "\nВведите сумму перевода: ";
    cin >> amount;

    if (amount < 1)
    {
        cout << "Сумма должна быть больше нуля.\n";
        return;
    }

    if (amount > 10000)
    {
        cout << "Максимальная сумма перевода — 10000.\n";
        return;
    }

    if (amount > balance)
    {
        cout << "Недостаточно денег.\n";
        return;
    }

    balance -= amount;

    cout << "Перевод выполнен.\n";
}

void showBalance()
{
    cout << "\nБаланс: " << balance << "\n";
}

int main()
{
    int choice;

    do
    {
        cout << "\n========= BANK =========\n";
        cout << "1. Перевести деньги\n";
        cout << "2. Баланс\n";
        cout << "0. Выход\n";

        cin >> choice;

        switch (choice)
        {
            case 1:
                transfer();
                break;

            case 2:
                showBalance();
                break;
        }

    } while (choice != 0);

    return 0;
}
