using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — WEAPON SHOOTING
Язык: C#
Формат: самостоятельная работа
Тема: Positive / Negative Testing
============================================================

ОПИСАНИЕ

Программа имитирует стрельбу игрового оружия.

В магазине оружия находится 10 патронов.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Начальное количество патронов — 10.

2. Количество выстрелов должно быть больше 0.

3. Нельзя выполнить больше выстрелов, чем есть патронов.

4. После выстрелов количество патронов уменьшается.

5. Нельзя получить отрицательное количество патронов.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Создайте Positive и Negative Test Case.

Проверьте:

- 1 выстрел;
- несколько выстрелов;
- 10 выстрелов;
- 11 выстрелов;
- 0;
- отрицательное количество.

============================================================
*/

class Program
{
    static void Shoot()
    {
        int ammo = 10;

        Console.Write("Сколько раз выстрелить: ");
        int count = Convert.ToInt32(Console.ReadLine());

        if (count <= 0)
        {
            Console.WriteLine("Количество выстрелов некорректно.");
            return;
        }

        if (count > ammo)
        {
            Console.WriteLine("Недостаточно патронов.");
            return;
        }

        ammo -= count;

        Console.WriteLine("Выстрел выполнен.");
        Console.WriteLine($"Осталось патронов: {ammo}");
    }

    static void Main()
    {
        Shoot();
    }
}
