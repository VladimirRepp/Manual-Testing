using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — PROMO CODE
Язык: C#
Формат: самостоятельная работа
Тема: Positive / Negative Testing
============================================================

ОПИСАНИЕ

Программа рассчитывает скидку на заказ интернет-магазина.

Промокод GAME10 предоставляет скидку 10%.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Стоимость заказа должна быть больше 0.

2. Промокод GAME10 даёт скидку 10%.

3. При правильном промокоде итоговая стоимость должна
   уменьшаться на 10%.

4. При неправильном промокоде скидка не применяется.

5. Отрицательная стоимость заказа недопустима.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Создайте Positive и Negative Test Case.

Проверьте:

- корректный заказ + корректный промокод;
- корректный заказ + неправильный промокод;
- пустой промокод;
- 0 рублей;
- отрицательную стоимость.
============================================================
*/

class Program
{
    static void ApplyPromo()
    {
        Console.Write("Введите сумму заказа: ");
        double order = Convert.ToDouble(Console.ReadLine());

        Console.Write("Введите промокод: ");
        string promo = Console.ReadLine();

        if (order <= 0)
        {
            Console.WriteLine("Некорректная сумма.");
            return;
        }

        if (promo == "GAME10")
        {
            double discount = order * 0.10;
            order -= discount;

            Console.WriteLine($"Итоговая сумма: {order}");
        }
        else
        {
            Console.WriteLine("Промокод недействителен.");
        }
    }

    static void Main()
    {
        ApplyPromo();
    }
}
