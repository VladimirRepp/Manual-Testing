using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — ONLINE SHOP CART
Язык: C#
Формат: самостоятельная работа
Тема: основы тестирования
============================================================

ОПИСАНИЕ

Программа имитирует добавление товара в корзину интернет-магазина.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Цена одного товара — 1000 рублей.

2. Пользователь указывает количество товаров.

3. Количество должно быть положительным.

4. Стоимость заказа рассчитывается как:
   количество × цена.

5. При количестве 1 итоговая стоимость должна быть 1000 рублей.

6. Нельзя добавить в корзину 0 товаров.

7. Нельзя добавить отрицательное количество товаров.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Проверьте программу с:

- 1 товаром;
- 2 товарами;
- большим количеством;
- 0;
- отрицательным количеством.

Сравните ожидаемый и фактический результат.

============================================================
*/

class Program
{
    static int cartItems = 0;

    static void AddProduct()
    {
        Console.Write("Количество товаров: ");
        int count = Convert.ToInt32(Console.ReadLine());

        cartItems += count;

        Console.WriteLine("Товары добавлены в корзину.");
    }

    static void RemoveProduct()
    {
        Console.Write("Количество товаров: ");
        int count = Convert.ToInt32(Console.ReadLine());

        cartItems -= count;

        Console.WriteLine("Товары удалены.");
    }

    static void ShowCart()
    {
        Console.WriteLine($"\nВ корзине товаров: {cartItems}");
    }

    static void Main()
    {
        int choice;

        do
        {
            Console.WriteLine("\n========== SHOP ==========");
            Console.WriteLine("1. Добавить товар");
            Console.WriteLine("2. Удалить товар");
            Console.WriteLine("3. Показать корзину");
            Console.WriteLine("0. Выход");

            Console.Write("Выберите действие: ");
            choice = Convert.ToInt32(Console.ReadLine());

            switch (choice)
            {
                case 1:
                    AddProduct();
                    break;

                case 2:
                    RemoveProduct();
                    break;

                case 3:
                    ShowCart();
                    break;

                case 0:
                    break;

                default:
                    Console.WriteLine("Неизвестная команда.");
                    break;
            }

        } while (choice != 0);
    }
}
