using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — GAME CURRENCY SHOP
Язык: C#
Формат: самостоятельная работа
Тема: основы тестирования
============================================================

ОПИСАНИЕ

Программа имитирует покупку игровой валюты.

Пользователь имеет некоторое количество монет и может
купить игровой предмет.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. При запуске у пользователя 1000 монет.

2. Предмет стоит 300 монет.

3. Если монет достаточно, предмет должен быть куплен.

4. После покупки стоимость предмета должна быть вычтена
   из количества монет.

5. Если монет недостаточно, покупка невозможна.

6. Количество монет не должно становиться отрицательным.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Проверьте:

- покупку при достаточном количестве монет;
- покупку при недостаточном количестве монет;
- ситуацию, когда монет ровно столько, сколько стоит предмет;
- повторную покупку;
- изменение баланса после покупки.

Для каждой проверки определите:

1. Тестовые данные.
2. Ожидаемый результат.
3. Фактический результат.
4. Статус PASS / FAIL.

============================================================
*/

class Program
{
    static int coins = 1000;

    static void ShowCoins()
    {
        Console.WriteLine($"\nМонеты: {coins}");
    }

    static void BuyItem()
    {
        int price = 700;

        Console.WriteLine($"\nЦена предмета: {price}");

        if (coins >= price)
        {
            coins -= price;
            Console.WriteLine("Предмет куплен!");
        }
        else
        {
            Console.WriteLine("Недостаточно монет.");
        }
    }

    static void AddCoins()
    {
        Console.Write("\nВведите количество монет: ");
        int value = Convert.ToInt32(Console.ReadLine());

        coins += value;

        Console.WriteLine("Монеты добавлены.");
    }

    static void Main()
    {
        int choice;

        do
        {
            Console.WriteLine("\n========== GAME SHOP ==========");
            Console.WriteLine("1. Показать монеты");
            Console.WriteLine("2. Купить предмет");
            Console.WriteLine("3. Добавить монеты");
            Console.WriteLine("0. Выход");
            Console.WriteLine("===============================");

            Console.Write("Выберите действие: ");
            choice = Convert.ToInt32(Console.ReadLine());

            switch (choice)
            {
                case 1:
                    ShowCoins();
                    break;

                case 2:
                    BuyItem();
                    break;

                case 3:
                    AddCoins();
                    break;

                case 0:
                    break;

                default:
                    Console.WriteLine("Неизвестная команда.");
                    break;
            }

        } while (choice != 0);
    }
}
