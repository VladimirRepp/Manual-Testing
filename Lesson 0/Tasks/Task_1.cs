using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — CINEMA TICKET
Язык: C++
Формат: самостоятельная работа
Тема: основы тестирования
============================================================

ОПИСАНИЕ

Программа имитирует покупку билета в кинотеатр.

Пользователь указывает количество билетов и получает
стоимость заказа.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Один билет стоит 500 рублей.

2. Количество билетов должно быть положительным числом.

3. При покупке нескольких билетов стоимость должна
   рассчитываться как:
   количество билетов × 500 рублей.

4. Нельзя купить 0 билетов.

5. Нельзя купить отрицательное количество билетов.

6. Итоговая стоимость заказа не может быть отрицательной.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Проверьте программу с корректными и некорректными данными.

Минимум проверьте:

- 1 билет;
- 2 билета;
- 10 билетов;
- 0 билетов;
- отрицательное количество;
- другое некорректное значение.

Для каждой проверки укажите ожидаемый и фактический результат.

============================================================
*/

class Program
{
    static int coins = 1000;

    static void ShowCoins()
    {
        Console.WriteLine($"\nМонеты: {coins}");
    }

    static void BuyItem()
    {
        int price = 700;

        Console.WriteLine($"\nЦена предмета: {price}");

        if (coins >= price)
        {
            coins -= price;
            Console.WriteLine("Предмет куплен!");
        }
        else
        {
            Console.WriteLine("Недостаточно монет.");
        }
    }

    static void AddCoins()
    {
        Console.Write("\nВведите количество монет: ");
        int value = Convert.ToInt32(Console.ReadLine());

        coins += value;

        Console.WriteLine("Монеты добавлены.");
    }

    static void Main()
    {
        int choice;

        do
        {
            Console.WriteLine("\n========== GAME SHOP ==========");
            Console.WriteLine("1. Показать монеты");
            Console.WriteLine("2. Купить предмет");
            Console.WriteLine("3. Добавить монеты");
            Console.WriteLine("0. Выход");
            Console.WriteLine("===============================");

            Console.Write("Выберите действие: ");
            choice = Convert.ToInt32(Console.ReadLine());

            switch (choice)
            {
                case 1:
                    ShowCoins();
                    break;

                case 2:
                    BuyItem();
                    break;

                case 3:
                    AddCoins();
                    break;

                case 0:
                    break;

                default:
                    Console.WriteLine("Неизвестная команда.");
                    break;
            }

        } while (choice != 0);
    }
}
