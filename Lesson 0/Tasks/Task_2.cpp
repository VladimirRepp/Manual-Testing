#include <iostream>
using namespace std;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — CINEMA TICKET
Язык: C++
Формат: самостоятельная работа
Тема: основы тестирования
============================================================

ОПИСАНИЕ

Программа имитирует покупку билета в кинотеатр.

Пользователь указывает количество билетов и получает
стоимость заказа.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Один билет стоит 500 рублей.

2. Количество билетов должно быть положительным числом.

3. При покупке нескольких билетов стоимость должна
   рассчитываться как:
   количество билетов × 500 рублей.

4. Нельзя купить 0 билетов.

5. Нельзя купить отрицательное количество билетов.

6. Итоговая стоимость заказа не может быть отрицательной.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Проверьте программу с корректными и некорректными данными.

Минимум проверьте:

- 1 билет;
- 2 билета;
- 10 билетов;
- 0 билетов;
- отрицательное количество;
- другое некорректное значение.

Для каждой проверки укажите ожидаемый и фактический результат.

============================================================
*/


int tickets = 5;

void showTickets()
{
    cout << "\nСвободных билетов: " << tickets << "\n";
}

void buyTicket()
{
    int count;

    cout << "\nСколько билетов купить: ";
    cin >> count;

    if (count <= tickets)
    {
        tickets -= count;
        cout << "Билеты успешно куплены.\n";
    }
    else
    {
        cout << "Недостаточно билетов.\n";
    }
}

void returnTicket()
{
    int count;

    cout << "\nСколько билетов вернуть: ";
    cin >> count;

    tickets += count;

    cout << "Билеты возвращены.\n";
}

int main()
{
    int choice;

    do
    {
        cout << "\n========== CINEMA ==========\n";
        cout << "1. Свободные билеты\n";
        cout << "2. Купить билеты\n";
        cout << "3. Вернуть билеты\n";
        cout << "0. Выход\n";
        cout << "============================\n";

        cin >> choice;

        switch (choice)
        {
            case 1:
                showTickets();
                break;

            case 2:
                buyTicket();
                break;

            case 3:
                returnTicket();
                break;

            case 0:
                break;

            default:
                cout << "Неизвестная команда.\n";
        }

    } while (choice != 0);

    return 0;
}
