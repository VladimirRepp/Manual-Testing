#include <iostream>
using namespace std;

// Задание для разбора со студентами

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — GAME STORE
Язык: C++
Формат: разбираем вместе с преподавателем
Тема: основы тестирования
============================================================

ОПИСАНИЕ

Программа имитирует небольшой магазин компьютерных игр.

Пользователь может:
- посмотреть баланс;
- пополнить баланс;
- купить игру;
- посмотреть информацию о выбранной игре.

Цель тестировщика — проверить, соответствует ли поведение
программы заявленным требованиям.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. При запуске баланс пользователя равен 1000 рублей.

2. Пользователь может пополнить баланс.

3. Сумма пополнения должна быть положительным числом.

4. После пополнения баланс должен увеличиваться на указанную
   сумму.

5. Пользователь может купить игру стоимостью 500 рублей.

6. Если денег достаточно, покупка должна выполняться,
   а стоимость игры должна вычитаться из баланса.

7. Если денег недостаточно, покупка не должна выполняться.

8. После неуспешной покупки баланс не должен изменяться.

9. Баланс не должен становиться отрицательным.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Составьте набор проверок, который позволит убедиться,
что программа соответствует требованиям.

Обязательно проверьте:

- обычное пополнение баланса;
- пополнение на 0;
- пополнение отрицательной суммой;
- покупку при достаточном количестве денег;
- покупку при недостаточном количестве денег;
- ситуацию, когда денег ровно столько, сколько стоит игра;
- изменение баланса после операций.

Для каждой проверки определите:

1. Тестовые данные.
2. Ожидаемый результат.
3. Фактический результат.
4. Статус PASS / FAIL.

Не исправляйте код сразу после обнаружения проблемы.
Сначала зафиксируйте результат тестирования.

------------------------------------------------------------
ОЖИДАЕМЫЙ РЕЗУЛЬТАТ РАБОТЫ / КЛЮЧ ДЛЯ ПРЕПОДАВАТЕЛЯ
------------------------------------------------------------

Студент должен:

- понимать разницу между ожидаемым и фактическим результатом;
- составить несколько Test Case;
- найти проверки, в которых программа не соответствует требованиям;
- корректно оформить PASS / FAIL.

Возможные дефекты в программе:

1. Программа позволяет пополнять баланс отрицательной суммой.
   Это приводит к уменьшению баланса.

2. Возможна ситуация, при которой баланс становится
   некорректным из-за отрицательного пополнения.

Важно:
студент не обязан сразу найти все дефекты.
Основная цель занятия — научиться сравнивать
фактическое поведение программы с требованиями.

============================================================
*/

int balance = 2000;
int gamePrice = 1500;

void showBalance()
{
    cout << "\nВаш баланс: " << balance << " руб.\n";
}

void buyGame()
{
    cout << "\nИгра стоит " << gamePrice << " руб.\n";

    if (balance >= gamePrice)
    {
        balance -= gamePrice;
        cout << "Покупка выполнена!\n";
    }
    else
    {
        cout << "Недостаточно средств.\n";
    }
}

void addMoney()
{
    int money;

    cout << "\nВведите сумму пополнения: ";
    cin >> money;

    balance += money;

    cout << "Баланс пополнен.\n";
}

void showGame()
{
    cout << "\nНазвание игры: Cyber Racer\n";
    cout << "Цена: " << gamePrice << " руб.\n";
}

int main()
{
    int choice;

    do
    {
        cout << "\n========== GAME STORE ==========\n";
        cout << "1. Показать баланс\n";
        cout << "2. Купить игру\n";
        cout << "3. Пополнить баланс\n";
        cout << "4. Информация об игре\n";
        cout << "0. Выход\n";
        cout << "================================\n";

        cout << "Выберите действие: ";
        cin >> choice;

        switch (choice)
        {
            case 1:
                showBalance();
                break;

            case 2:
                buyGame();
                break;

            case 3:
                addMoney();
                break;

            case 4:
                showGame();
                break;

            case 0:
                cout << "Выход.\n";
                break;

            default:
                cout << "Неизвестная команда.\n";
        }

    } while (choice != 0);

    return 0;
}
