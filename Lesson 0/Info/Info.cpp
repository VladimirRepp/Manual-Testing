#include <iostream>
#include <string>

using namespace std;

void showTerm(int number)
{
    cout << "\n========================================\n";

    switch (number)
    {
        case 1:
            cout << "ТЕСТИРОВАНИЕ ПО\n\n";
            cout << "Тестирование программного обеспечения — это процесс "
                    "проверки программы, чтобы определить, соответствует ли "
                    "она требованиям и правильно ли работает.\n";
            break;

        case 2:
            cout << "QA (QUALITY ASSURANCE)\n\n";
            cout << "QA — обеспечение качества программного обеспечения.\n"
                    "QA включает процессы и действия, которые помогают "
                    "предотвращать ошибки и повышать качество продукта.\n";
            break;

        case 3:
            cout << "РУЧНОЕ ТЕСТИРОВАНИЕ\n\n";
            cout << "Ручное тестирование — проверка программы человеком "
                    "без использования автоматических тестов для выполнения "
                    "проверок.\n";
            break;

        case 4:
            cout << "АВТОМАТИЗИРОВАННОЕ ТЕСТИРОВАНИЕ\n\n";
            cout << "Автоматизированное тестирование — выполнение "
                    "проверок программой или специальным инструментом "
                    "без постоянного участия человека.\n";
            break;

        case 5:
            cout << "ТРЕБОВАНИЕ\n\n";
            cout << "Требование описывает, что программа должна делать "
                    "или каким требованиям должна соответствовать.\n";
            break;

        case 6:
            cout << "ОЖИДАЕМЫЙ РЕЗУЛЬТАТ\n\n";
            cout << "Ожидаемый результат — то, что должно произойти, "
                    "если программа работает правильно.\n";
            break;

        case 7:
            cout << "ФАКТИЧЕСКИЙ РЕЗУЛЬТАТ\n\n";
            cout << "Фактический результат — то, что действительно произошло "
                    "при выполнении действия в программе.\n";
            break;

        case 8:
            cout << "BUG / ДЕФЕКТ\n\n";
            cout << "Дефект — ошибка в программе, из-за которой фактическое "
                    "поведение отличается от ожидаемого.\n";
            break;

        case 9:
            cout << "SUT (SYSTEM UNDER TEST)\n\n";
            cout << "SUT — система, которую в данный момент тестируют.\n"
                    "Это может быть программа, игра, сайт, API или отдельный "
                    "модуль системы.\n";
            break;

        case 10:
            cout << "ТЕСТОВЫЙ СЦЕНАРИЙ\n\n";
            cout << "Тестовый сценарий — описание того, что необходимо "
                    "проверить в программе.\n";
            break;

        case 11:
            cout << "TEST CASE\n\n";
            cout << "Test Case — подробная проверка, содержащая условия, "
                    "шаги выполнения, тестовые данные и ожидаемый результат.\n";
            break;

        case 12:
            cout << "CHECKLIST\n\n";
            cout << "Checklist — список проверок, которые необходимо "
                    "выполнить. В отличие от Test Case, обычно содержит "
                    "краткие пункты без подробных шагов.\n";
            break;

        default:
            cout << "Такого термина нет.\n";
    }

    cout << "========================================\n";
}

void showMenu()
{
    cout << "\n";
    cout << "========== ТЕРМИНЫ QA ==========\n";
    cout << "1. Тестирование ПО\n";
    cout << "2. QA\n";
    cout << "3. Ручное тестирование\n";
    cout << "4. Автоматизированное тестирование\n";
    cout << "5. Требование\n";
    cout << "6. Ожидаемый результат\n";
    cout << "7. Фактический результат\n";
    cout << "8. Bug / Дефект\n";
    cout << "9. SUT\n";
    cout << "10. Тестовый сценарий\n";
    cout << "11. Test Case\n";
    cout << "12. Checklist\n";
    cout << "0. Выход\n";
    cout << "================================\n";
}

int main()
{
    int choice;

    do
    {
        showMenu();

        cout << "Выберите термин: ";
        cin >> choice;

        if (choice != 0)
        {
            showTerm(choice);
        }

    } while (choice != 0);

    cout << "\nПрограмма завершена.\n";

    return 0;
}