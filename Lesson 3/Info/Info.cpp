#include <iostream>

using namespace std;

void showTerm(int number)
{
    cout << "\n========================================\n";

    switch (number)
    {
        case 1:
            cout << "ГРАНИЧНОЕ ЗНАЧЕНИЕ\n\n";
            cout << "Значение, находящееся на границе допустимого "
                    "диапазона или рядом с ней.\n";
            break;

        case 2:
            cout << "BOUNDARY VALUE ANALYSIS\n\n";
            cout << "Анализ граничных значений — техника тест-дизайна, "
                    "при которой особое внимание уделяется значениям "
                    "на границах диапазона.\n";
            break;

        case 3:
            cout << "ДОПУСТИМЫЙ ДИАПАЗОН\n\n";
            cout << "Диапазон значений, которые программа должна принимать.\n"
                    "Например: возраст от 18 до 65.\n";
            break;

        case 4:
            cout << "МИНИМАЛЬНОЕ ЗНАЧЕНИЕ\n\n";
            cout << "Наименьшее значение, которое считается допустимым.\n";
            break;

        case 5:
            cout << "МАКСИМАЛЬНОЕ ЗНАЧЕНИЕ\n\n";
            cout << "Наибольшее значение, которое считается допустимым.\n";
            break;

        case 6:
            cout << "ЗНАЧЕНИЕ НИЖЕ МИНИМУМА\n\n";
            cout << "Значение, которое находится непосредственно "
                    "ниже разрешенной нижней границы.\n";
            break;

        case 7:
            cout << "ЗНАЧЕНИЕ ВЫШЕ МАКСИМУМА\n\n";
            cout << "Значение, которое находится непосредственно "
                    "выше разрешенной верхней границы.\n";
            break;

        case 8:
            cout << "ВНУТРЕННЕЕ ЗНАЧЕНИЕ\n\n";
            cout << "Значение, которое находится внутри допустимого "
                    "диапазона и не является его границей.\n";
            break;

        case 9:
            cout << "ГРАНИЧНАЯ ОШИБКА\n\n";
            cout << "Ошибка, связанная с неправильной обработкой "
                    "границы допустимого диапазона.\n"
                    "Например, программа должна принимать возраст 18, "
                    "но ошибочно принимает только значения больше 18.\n";
            break;

        case 10:
            cout << "ДИАПАЗОН\n\n";
            cout << "Набор значений между минимальной и максимальной "
                    "границами.\n";
            break;

        case 11:
            cout << "ЭКВИВАЛЕНТНЫЙ КЛАСС\n\n";
            cout << "Группа значений, которые программа должна обрабатывать "
                    "одинаковым образом.\n";
            break;

        case 12:
            cout << "EQUIVALENCE PARTITIONING\n\n";
            cout << "Разбиение входных данных на группы, внутри которых "
                    "значения считаются эквивалентными с точки зрения тестирования.\n";
            break;

        default:
            cout << "Такого термина нет.\n";
    }

    cout << "========================================\n";
}

void showMenu()
{
    cout << "\n========== ГРАНИЧНЫЕ ЗНАЧЕНИЯ ==========\n";
    cout << "1. Граничное значение\n";
    cout << "2. Boundary Value Analysis\n";
    cout << "3. Допустимый диапазон\n";
    cout << "4. Минимальное значение\n";
    cout << "5. Максимальное значение\n";
    cout << "6. Значение ниже минимума\n";
    cout << "7. Значение выше максимума\n";
    cout << "8. Внутреннее значение\n";
    cout << "9. Граничная ошибка\n";
    cout << "10. Диапазон\n";
    cout << "11. Эквивалентный класс\n";
    cout << "12. Equivalence Partitioning\n";
    cout << "0. Выход\n";
    cout << "=========================================\n";
}

int main()
{
    int choice;

    do
    {
        showMenu();

        cout << "Выберите термин: ";
        cin >> choice;

        if (choice != 0)
        {
            showTerm(choice);
        }

    } while (choice != 0);

    return 0;
}