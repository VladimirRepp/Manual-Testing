using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — GAME RATING
Язык: C#
Формат: разбираем вместе с преподавателем
Тема: Boundary Value Analysis
============================================================

ОПИСАНИЕ

Программа проверяет рейтинг игрока.

Рейтинг используется для определения допустимости
участия игрока в рейтинговом соревновании.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Минимальный допустимый рейтинг — 1000.

2. Максимальный допустимый рейтинг — 3000.

3. Значение 1000 допустимо.

4. Значение 3000 допустимо.

5. Значения меньше 1000 недопустимы.

6. Значения больше 3000 недопустимы.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Используйте Boundary Value Analysis.

Проверьте как минимум:

- 999;
- 1000;
- 1001;
- значение внутри диапазона;
- 2999;
- 3000;
- 3001.

Для каждого значения определите:

- ожидаемый результат;
- фактический результат;
- PASS / FAIL.

После выполнения объясните:

1. Где находятся границы допустимого диапазона?
2. Какие значения относятся к границам?
3. Какие значения находятся непосредственно за границами?

------------------------------------------------------------
ОЖИДАЕМЫЙ РЕЗУЛЬТАТ / КЛЮЧ ДЛЯ ПРЕПОДАВАТЕЛЯ
------------------------------------------------------------

Ожидаемый набор:

999  — FAIL
1000 — PASS
1001 — PASS
1500 — PASS
2999 — PASS
3000 — PASS
3001 — FAIL

В программе предусмотрена ошибка на одной из границ.

Главная учебная цель — показать, что проверки только
1000, 1500 и 3000 недостаточно.

Студент должен проверить значения непосредственно
около границ.

============================================================
*/

class Program
{
    static void CheckRating()
    {
        Console.Write("\nВведите рейтинг: ");
        int rating = Convert.ToInt32(Console.ReadLine());

        if (rating >= 1000 && rating <= 3000)
        {
            Console.WriteLine("Рейтинг допустим.");
        }
        else
        {
            Console.WriteLine("Рейтинг недопустим.");
        }
    }

    static void Main()
    {
        int choice;

        do
        {
            Console.WriteLine("\n========= GAME RATING =========");
            Console.WriteLine("1. Проверить рейтинг");
            Console.WriteLine("0. Выход");

            Console.Write("Выберите действие: ");
            choice = Convert.ToInt32(Console.ReadLine());

            if (choice == 1)
            {
                CheckRating();
            }

        } while (choice != 0);
    }
}
