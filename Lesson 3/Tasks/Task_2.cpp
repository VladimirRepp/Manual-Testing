#include <iostream>
using namespace std;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — SHOP QUANTITY
Язык: C++
Формат: самостоятельная работа
Тема: Boundary Value Analysis
============================================================

ОПИСАНИЕ

Программа позволяет добавить товар в корзину.

За одну операцию можно добавить от 1 до 20 единиц товара.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

1. Минимальное количество — 1.

2. Максимальное количество — 20.

3. Значения от 1 до 20 включительно допустимы.

4. Значения 0 и меньше недопустимы.

5. Значения больше 20 недопустимы.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

Проведите Boundary Value Analysis.

Обязательно проверьте значения:

0, 1, 2, 10, 19, 20, 21.

Зафиксируйте ожидаемый и фактический результат.

============================================================
*/

void checkQuantity()
{
    int quantity;

    cout << "Введите количество товаров: ";
    cin >> quantity;

    if (quantity >= 1 && quantity <= 20)
    {
        cout << "Количество допустимо.\n";
    }
    else
    {
        cout << "Количество недопустимо.\n";
    }
}

int main()
{
    int choice;

    do
    {
        cout << "\n========= SHOP =========\n";
        cout << "1. Проверить количество\n";
        cout << "0. Выход\n";

        cin >> choice;

        if (choice == 1)
        {
            checkQuantity();
        }

    } while (choice != 0);

    return 0;
}
