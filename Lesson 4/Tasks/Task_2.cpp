#include <iostream>
using namespace std;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — GAME BONUS
Язык: C++
Формат: самостоятельная работа
Тема: Equivalence Partitioning + Decision Table
============================================================

ОПИСАНИЕ

Игра выдаёт игроку бонус.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

Игрок получает бонус, если выполняется хотя бы одно условие:

1. Уровень игрока не меньше 20.

ИЛИ

2. Игрок имеет статус VIP.

Если оба условия ложны, бонус не выдаётся.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

1. Определите классы эквивалентности для уровня.

2. Определите классы для статуса VIP.

3. Составьте Decision Table.

Обязательно проверьте четыре основные комбинации:

- уровень < 20 + не VIP;
- уровень < 20 + VIP;
- уровень >= 20 + не VIP;
- уровень >= 20 + VIP.

Для каждой комбинации укажите ожидаемый результат.

============================================================
*/

void checkBonus()
{
    int level;
    int vip;

    cout << "Уровень игрока: ";
    cin >> level;

    cout << "VIP?\n";
    cout << "1 - Да\n";
    cout << "0 - Нет\n";
    cin >> vip;

    if (level >= 20 || vip == 1)
    {
        cout << "Игрок получает бонус.\n";
    }
    else
    {
        cout << "Бонус не предоставляется.\n";
    }
}

int main()
{
    int choice;

    do
    {
        cout << "\n======= GAME BONUS =======\n";
        cout << "1. Проверить бонус\n";
        cout << "0. Выход\n";

        cin >> choice;

        if (choice == 1)
        {
            checkBonus();
        }

    } while (choice != 0);

    return 0;
}
