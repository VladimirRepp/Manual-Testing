using System;

/*
============================================================
ПРАКТИЧЕСКОЕ ЗАДАНИЕ — GAME MODE ACCESS
Язык: C#
Формат: самостоятельная работа
Тема: Equivalence Partitioning + Decision Table
============================================================

ОПИСАНИЕ

В игре существует специальный игровой режим.

Доступ к режиму зависит от уровня игрока и наличия
Premium-статуса.

------------------------------------------------------------
ТРЕБОВАНИЯ
------------------------------------------------------------

Игрок получает доступ к режиму, если выполняется
хотя бы одно условие:

1. Уровень игрока не меньше 30.

ИЛИ

2. У игрока есть Premium.

Если оба условия не выполнены, доступ запрещён.

------------------------------------------------------------
ЗАДАНИЕ ТЕСТИРОВЩИКА
------------------------------------------------------------

1. Определите классы эквивалентности для уровня.

2. Определите классы для Premium-статуса.

3. Создайте Decision Table.

Проверьте минимум четыре комбинации:

- уровень < 30 + не Premium;
- уровень < 30 + Premium;
- уровень >= 30 + не Premium;
- уровень >= 30 + Premium.

Для каждой комбинации определите ожидаемый результат.

============================================================
*/

class Program
{
    static void CheckAccess()
    {
        Console.Write("Уровень игрока: ");
        int level = Convert.ToInt32(Console.ReadLine());

        Console.Write("Есть Premium? 1/0: ");
        int premium = Convert.ToInt32(Console.ReadLine());

        if (level >= 30 || premium == 1)
        {
            Console.WriteLine("Доступ разрешен.");
        }
        else
        {
            Console.WriteLine("Доступ запрещен.");
        }
    }

    static void Main()
    {
        int choice;

        do
        {
            Console.WriteLine("\n======= GAME MODE =======");
            Console.WriteLine("1. Проверить доступ");
            Console.WriteLine("0. Выход");

            Console.Write("Выберите действие: ");
            choice = Convert.ToInt32(Console.ReadLine());

            if (choice == 1)
            {
                CheckAccess();
            }

        } while (choice != 0);
    }
}
