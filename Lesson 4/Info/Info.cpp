#include <iostream>

using namespace std;

void showTerm(int number)
{
    cout << "\n========================================\n";

    switch (number)
    {
        case 1:
            cout << "ЭКВИВАЛЕНТНЫЙ КЛАСС\n\n";
            cout << "Группа входных значений, которые должны "
                    "обрабатываться программой одинаковым образом.\n";
            break;

        case 2:
            cout << "EQUIVALENCE PARTITIONING\n\n";
            cout << "Техника тест-дизайна, при которой входные данные "
                    "разделяются на классы эквивалентности.\n";
            break;

        case 3:
            cout << "ВАЛИДНЫЙ КЛАСС\n\n";
            cout << "Класс данных, значения которого соответствуют "
                    "требованиям программы.\n";
            break;

        case 4:
            cout << "НЕВАЛИДНЫЙ КЛАСС\n\n";
            cout << "Класс данных, значения которого не соответствуют "
                    "требованиям программы.\n";
            break;

        case 5:
            cout << "ПРЕДСТАВИТЕЛЬ КЛАССА\n\n";
            cout << "Конкретное значение, выбранное для проверки "
                    "эквивалентного класса.\n"
                    "Например, для класса 18-65 можно взять значение 30.\n";
            break;

        case 6:
            cout << "DECISION TABLE\n\n";
            cout << "Таблица решений — способ описать поведение программы "
                    "для различных комбинаций условий.\n";
            break;

        case 7:
            cout << "УСЛОВИЕ\n\n";
            cout << "Условие — некоторое обстоятельство, которое влияет "
                    "на поведение программы.\n"
                    "Например: пользователь является VIP.\n";
            break;

        case 8:
            cout << "ПРАВИЛО\n\n";
            cout << "Правило в таблице решений описывает, что должна сделать "
                    "программа при определенной комбинации условий.\n";
            break;

        case 9:
            cout << "КОМБИНАЦИЯ УСЛОВИЙ\n\n";
            cout << "Набор одновременно выполняющихся условий.\n"
                    "Например: VIP = да и сумма заказа >= 5000.\n";
            break;

        case 10:
            cout << "ЛОГИЧЕСКОЕ AND\n\n";
            cout << "Оператор AND означает «И».\n"
                    "Все связанные условия должны быть истинными.\n";
            break;

        case 11:
            cout << "ЛОГИЧЕСКОЕ OR\n\n";
            cout << "Оператор OR означает «ИЛИ».\n"
                    "Достаточно, чтобы истинным было хотя бы одно условие.\n";
            break;

        case 12:
            cout << "ТЕСТОВАЯ КОМБИНАЦИЯ\n\n";
            cout << "Конкретный набор входных данных, выбранный "
                    "для проверки определенного сочетания условий.\n";
            break;

        default:
            cout << "Такого термина нет.\n";
    }

    cout << "========================================\n";
}

void showMenu()
{
    cout << "\n======= ЭКВИВАЛЕНТНЫЕ КЛАССЫ =======\n";
    cout << "1. Эквивалентный класс\n";
    cout << "2. Equivalence Partitioning\n";
    cout << "3. Валидный класс\n";
    cout << "4. Невалидный класс\n";
    cout << "5. Представитель класса\n";
    cout << "6. Decision Table\n";
    cout << "7. Условие\n";
    cout << "8. Правило\n";
    cout << "9. Комбинация условий\n";
    cout << "10. Логическое AND\n";
    cout << "11. Логическое OR\n";
    cout << "12. Тестовая комбинация\n";
    cout << "0. Выход\n";
    cout << "=====================================\n";
}

int main()
{
    int choice;

    do
    {
        showMenu();

        cout << "Выберите термин: ";
        cin >> choice;

        if (choice != 0)
        {
            showTerm(choice);
        }

    } while (choice != 0);

    return 0;
}